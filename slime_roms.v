//-----------------------------------------------------------------------------
// Maze map : 20 x 15 tiles, each tile is 32 x 32 pixels.  wall = 1 means wall.
// To change the maze, edit the rows below (left tile = leftmost bit).
//-----------------------------------------------------------------------------
module maze_rom (
    input  wire [4:0] tx,      // tile column 0 .. 19
    input  wire [3:0] ty,      // tile row    0 .. 14
    output wire       wall
);
    reg [19:0] row;
    always @* begin
        case (ty)
            4'd0 : row = 20'b11111111111111111111;
            4'd1 : row = 20'b10000000011000000001;
            4'd2 : row = 20'b10110111011011101101;
            4'd3 : row = 20'b10000000000000000001;
            4'd4 : row = 20'b10110101111110101101;
            4'd5 : row = 20'b10000100011000100001;
            4'd6 : row = 20'b11110111011011101111;
            4'd7 : row = 20'b10000000000000000001;
            4'd8 : row = 20'b11110111011011101111;
            4'd9 : row = 20'b10000100011000100001;
            4'd10: row = 20'b10110101111110101101;
            4'd11: row = 20'b10000000000000000001;
            4'd12: row = 20'b10110111011011101101;
            4'd13: row = 20'b10000000011000000001;
            4'd14: row = 20'b11111111111111111111;
            default: row = 20'hFFFFF;
        endcase
    end
    assign wall = (tx > 5'd19) ? 1'b1 : row[5'd19 - tx];
endmodule


